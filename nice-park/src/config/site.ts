// ---- Калькулятор доходу ----
export const calculator = {
  min: 10_000,
  max: 40_000,
  step: 500,
  defaultValue: 25_000,
  /** Поріг (план) за тиждень, після якого діє підвищений відсоток */
  threshold: 25_000,
  /** Частка водія до порогу */
  baseShare: 0.6,
  /** Частка водія з суми понад поріг */
  bonusShare: 0.65,
  /** Пальне (газ) як частка від каси */
  fuelRate: 0.26,
  /** Тижнів у місяці */
  weeksPerMonth: 4.33,
};

export type CalcResult = {
  gross: number;
  driverShare: number;
  fuel: number;
  ownerShare: number;
  netWeek: number;
  netMonth: number;
};

export function calculateIncome(gross: number): CalcResult {
  const c = calculator;
  const base = Math.min(gross, c.threshold) * c.baseShare;
  const bonus = Math.max(gross - c.threshold, 0) * c.bonusShare;
  const driverShare = base + bonus;
  const fuel = gross * c.fuelRate;
  const netWeek = driverShare - fuel;
  return {
    gross,
    driverShare,
    fuel,
    ownerShare: gross - driverShare,
    netWeek,
    netMonth: netWeek * c.weeksPerMonth,
  };
}

